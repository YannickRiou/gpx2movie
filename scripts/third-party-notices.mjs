// ---------- helpers ----------

mkdirSync(join(CACHE, 'spdx'), { recursive: true })
let lastRequest = 0
async function get(url, tries = 3) {
  for (let i = 1; ; i++) {
    const wait = lastRequest + 1100 - Date.now()
    if (wait > 0) await new Promise((r) => setTimeout(r, wait))
    lastRequest = Date.now()
    const res = await fetch(url, { headers: { 'User-Agent': USER_AGENT } })
    if (res.ok) return res
    if (res.status === 404 || i >= tries) throw new Error(`${url}: HTTP ${res.status}`)
    await new Promise((r) => setTimeout(r, 10_000 * i))
  }
}

const cratesFile = join(CACHE, 'crates.json')
const crateCache = existsSync(cratesFile) ? JSON.parse(readFileSync(cratesFile, 'utf8')) : {}

async function crateLicence(name, version) {
  const key = `${name}@${version}`
  if (!(key in crateCache)) {
    const json = await (await get(`https://crates.io/api/v1/crates/${name}/${version}`)).json()
    crateCache[key] = json.version?.license ?? null
    writeFileSync(cratesFile, JSON.stringify(crateCache, null, 1))
    process.stderr.write(`\r${Object.keys(crateCache).length} crates`)
  }
  return crateCache[key]
}

async function spdxText(id) {
  const file = join(CACHE, 'spdx', `${id}.txt`)
  if (!existsSync(file)) {
    const url = `https://raw.githubusercontent.com/spdx/license-list-data/main/text/${id}.txt`
    writeFileSync(file, await (await get(url)).text())
  }
  return sh(readFileSync(file, 'utf8'))
}

/** Parses an SPDX expression: returns { ids, ok } where ok = redistributable under MIT with these notices. */
function analyse(expr) {
  const ids = new Set()
  if (!expr) return { ids, ok: false }
  const tokens = expr.replace(/\//g, ' OR ').match(/\(|\)|[^\s()]+/g)
  let i = 0
  const orExpr = () => {
    let ok = andExpr()
    while (tokens[i] === 'OR') {
      i++
      ok = andExpr() || ok
    }
    return ok
  }
  const andExpr = () => {
    let ok = atom()
    while (tokens[i] === 'AND') {
      i++
      ok = atom() && ok
    }
    return ok
  }
  const atom = () => {
    if (tokens[i] === '(') {
      i++
      const ok = orExpr()
      i++
      return ok
    }
    const id = tokens[i++].replace(/\+$/, '')
    ids.add(id)
    const ok = PERMISSIVE.has(id)
    if (tokens[i] === 'WITH') {
      ids.add(tokens[++i])
      i++
    }
    return ok
  }
  return { ids, ok: orExpr() }
}

// ---------- npm ----------

const lock = JSON.parse(readFileSync(join(ROOT, 'package-lock.json'), 'utf8'))
const LICENCE_FILE = /^(licen[cs]e|copying|notice)/i
const npm = []
for (const [path, meta] of Object.entries(lock.packages)) {
  if (!path || meta.dev) continue
  const dir = join(ROOT, path)
  if (!existsSync(dir)) throw new Error(`${path} is not installed: run npm ci`)
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const files = readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort()
  const text = files
    .map((f) => (files.length > 1 ? `--- ${f} ---\n` : '') + sh(readFileSync(join(dir, f), 'utf8')))
    .join('\n\n')
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  npm.push({
    name: path.replace(/^node_modules\//, ''),
    version: pkg.version,
    licence: pkg.license ?? meta.license ?? (/^MIT License/i.test(text) ? 'MIT' : text ? 'see text' : null),
    text,
    author: typeof pkg.author === 'string' ? pkg.author : (pkg.author?.name ?? ''),
    repo: (repo ?? '').replace(/^git\+/, '').replace(/\.git$/, ''),
  })
}
npm.sort((a, b) => a.name.localeCompare(b.name))

// ---------- Rust ----------

const lockfile = readFileSync(join(ROOT, 'src-tauri/Cargo.lock'), 'utf8').replace(/\r\n/g, '\n')
const cargo = [...lockfile.matchAll(/\[\[package\]\]\nname = "([^"]+)"\nversion = "([^"]+)"\n(source = "registry[^\n]*)?/g)]
  .filter((m) => m[3])
  .map((m) => ({ name: m[1], version: m[2] }))
for (const c of cargo) c.licence = await crateLicence(c.name, c.version)
process.stderr.write('\n')

// ---------- licence review and standard texts ----------

const flagged = []
const alternatives = []
const standardIds = new Set(['MIT'])
for (const p of npm) {
  const { ids, ok } = analyse(p.licence === 'see text' ? null : p.licence)
  if (!ok) flagged.push(`npm ${p.name}@${p.version}: ${p.licence ?? 'no licence declared'}`)
  if (!p.text) ids.forEach((id) => PERMISSIVE.has(id) && standardIds.add(id))
}
for (const c of cargo) {
  const { ids, ok } = analyse(c.licence)
  if (!ok) flagged.push(`crate ${c.name} ${c.version}: ${c.licence ?? 'no licence declared on crates.io'}`)
  if (ok && [...ids].some((id) => !PERMISSIVE.has(id))) alternatives.push(`${c.name} ${c.version} (${c.licence})`)
  ids.forEach((id) => PERMISSIVE.has(id) && standardIds.add(id))
}
const mplNpm = npm.filter((p) => /MPL/.test(p.licence)).map((p) => p.name)
const mplCrates = cargo.filter((c) => /MPL/.test(c.licence ?? '')).map((c) => `${c.name} ${c.version} (${c.licence})`)

// ---------- output ----------

const out = []
out.push(`# Third-party notices

OpenFlyover itself is under the MIT license (see [LICENSE](LICENSE)). It redistributes the components below, each under
its own license. This file is generated by \`npm run notices\` (\`scripts/third-party-notices.mjs\`): do not edit it by hand.

Map tiles, terrain, weather and landmarks are downloaded at run time from open services and are not redistributed;
their attributions and licenses are in [docs/sources.md](docs/sources.md). The video encoder of the Linux desktop
application is the system's ffmpeg, which is not bundled.

## Licence review
`)
out.push(
  flagged.length
    ? `Components whose license is not on the permissive list of the generator (to review by hand):\n\n${flagged.map((f) => `- ${f}`).join('\n')}`
    : 'No GPL, LGPL, AGPL, SSPL, unknown or missing license is required by the components below.',
)
if (alternatives.length)
  out.push(`
Offered under a copyleft alternative too; the permissive option applies: ${alternatives.join(', ')}.`)
out.push(
  `\nFile-level copyleft (MPL-2.0): usable as is, the source of a modified file must be published. ` +
    (mplNpm.length ? `npm: ${mplNpm.join(', ')}. ` : '') +
    (mplCrates.length ? `Rust: ${mplCrates.join(', ')}.` : ''),
)

out.push('\n## Bundled assets\n')
for (const a of ASSETS) {
  out.push(`### ${a.name}\n\nLicense: ${a.licence}. ${a.note}\n`)
  if (a.text) out.push('```text\n' + a.text() + '\n```\n')
}

out.push(
  `## npm packages (${npm.length})\n\nProduction dependencies of \`package.json\` and their transitive dependencies (some are only partly or not at all in a given build).\n`,
)
const groups = new Map()
for (const p of npm) {
  const noText = !p.text
  const hint = noText
    ? ` (no license file in the package; standard text below${p.author ? `; author ${p.author.replace(/ <.*>/, '')}` : ''}${p.repo ? `; ${p.repo}` : ''})`
    : ''
  out.push(`- ${p.name} ${p.version}: ${p.licence ?? 'unknown'}${hint}`)
  if (!noText) groups.set(p.text, [...(groups.get(p.text) ?? []), `${p.name} ${p.version}`])
}
out.push('\n### License texts of the npm packages\n')
for (const [text, users] of [...groups].sort((a, b) => b[1].length - a[1].length)) {
  out.push(`#### ${users.join(', ')}\n\n` + '```text\n' + text + '\n```\n')
}

out.push(
  `## Rust crates (${cargo.length})\n\nEvery registry crate of \`src-tauri/Cargo.lock\`, including those used only on one operating system or at build time. License as declared on crates.io; the copyright notice of each crate is in its source, <https://crates.io/crates/NAME/VERSION>.\n`,
)
for (const c of cargo) out.push(`- ${c.name} ${c.version}: ${c.licence ?? 'unknown'}`)

out.push(
  '\n## Standard license texts\n\nReferenced above by their SPDX identifier (texts from <https://spdx.org/licenses/>; the copyright holders are those named by each component).\n',
)
for (const id of [...standardIds].sort()) {
  try {
    out.push(`### ${id}\n\n` + '```text\n' + (await spdxText(id)) + '\n```\n')
  } catch (e) {
    console.error(`no standard text for ${id}: ${e.message}`)
  }
}

writeFileSync(join(ROOT, 'THIRD_PARTY_NOTICES.md'), out.join('\n') + '\n')
console.error(`${npm.length} npm packages, ${cargo.length} crates, ${standardIds.size} standard texts`)
if (flagged.length) console.error(`TO REVIEW:\n${flagged.join('\n')}`)
